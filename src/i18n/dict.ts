/** 決まった言葉を引く */
export function tr(lang: Lang, key: Key): string {
  return dicts[lang].d[key] ?? ja[key];
}
/** この言語の辞書は人の確認が済んでいるか（済んでいなければ画面に「機械翻訳」と出す） */
export const isReviewed = (lang: Lang) => dicts[lang].reviewed;
/** 単位（個・斤・枚）を訳す。辞書に無い単位はそのまま */
export function trUnit(lang: Lang, unit: string): string {
  const k = `unit_${unit}` as Key;
  return k in ja ? tr(lang, k) : unit;
}
